import { Router } from "express";

import { protect } from "../../middlewares/auth.middleware.js";

import { prisma } from "../../lib/prismadb.js";

import {
  MessageAttachmentController,
} from "../../controllers/chat/message-attachment.controller.js";

import {
  MessageAttachmentService,
} from "../../chat/services/message-attachment.service.js";

import {
  PrismaMessageAttachmentGateway,
} from "../../chat/gateways/prisma-message-attachment.gateway.js";

import {
  MessageAttachmentPolicy,
} from "../../chat/policies/message-attachment.policy.js";

const router = Router();

////////////////////////////////////////////////////////////
// GATEWAY
////////////////////////////////////////////////////////////

const attachmentGateway =
  new PrismaMessageAttachmentGateway(
    prisma,
  );

////////////////////////////////////////////////////////////
// POLICY
////////////////////////////////////////////////////////////

const attachmentPolicy =
  new MessageAttachmentPolicy();

////////////////////////////////////////////////////////////
// SERVICE
////////////////////////////////////////////////////////////

const attachmentService =
  new MessageAttachmentService(
    attachmentGateway,
    attachmentPolicy,
  );

////////////////////////////////////////////////////////////
// CONTROLLER
////////////////////////////////////////////////////////////

const controller =
  new MessageAttachmentController(
    attachmentService,
  );

////////////////////////////////////////////////////////////
// UPLOAD / CREATE
////////////////////////////////////////////////////////////

router.post(
  "/",
  protect,
  controller.upload.bind(controller),
);

////////////////////////////////////////////////////////////
// SEARCH
////////////////////////////////////////////////////////////

router.get(
  "/search",
  protect,
  controller.search.bind(controller),
);

////////////////////////////////////////////////////////////
// LIST ATTACHMENTS FOR MESSAGE
////////////////////////////////////////////////////////////

router.get(
  "/message/:messageId",
  protect,
  controller.list.bind(controller),
);

////////////////////////////////////////////////////////////
// FIND BY ID
////////////////////////////////////////////////////////////

router.get(
  "/:attachmentId",
  protect,
  controller.findById.bind(controller),
);

////////////////////////////////////////////////////////////
// DELETE
////////////////////////////////////////////////////////////

router.delete(
  "/:attachmentId",
  protect,
  controller.delete.bind(controller),
);

export default router;