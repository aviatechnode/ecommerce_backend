import { Router } from "express";

import { protect } from "../../middlewares/auth.middleware.js";

import { PrismaSupportTeamMemberGateway } from "../../chat/gateways/prisma-support-team-member.gateway.js";

import { SupportTeamMemberService } from "../../chat/services/support-team-member.service.js";

import { SupportTeamMemberPolicy } from "../../chat/policies/support-team-member.policy.js";

import { SupportTeamMemberController } from "../../controllers/chat/support-team-member.controller.js";

import { prisma } from "../../lib/prismadb.js";

const router = Router();

////////////////////////////////////////////////////////////
// GATEWAY
////////////////////////////////////////////////////////////

const memberGateway =
  new PrismaSupportTeamMemberGateway(
    prisma,
  );

////////////////////////////////////////////////////////////
// POLICY
////////////////////////////////////////////////////////////

const memberPolicy =
  new SupportTeamMemberPolicy();

////////////////////////////////////////////////////////////
// SERVICE
////////////////////////////////////////////////////////////

const memberService =
  new SupportTeamMemberService(
    memberGateway,
    memberPolicy,
  );

////////////////////////////////////////////////////////////
// CONTROLLER
////////////////////////////////////////////////////////////

const controller =
  new SupportTeamMemberController(
    memberService,
  );

////////////////////////////////////////////////////////////
// ADD MEMBER
////////////////////////////////////////////////////////////

router.post(
  "/",
  protect,
  controller.add.bind(controller),
);

////////////////////////////////////////////////////////////
// LIST TEAM MEMBERS
////////////////////////////////////////////////////////////

router.get(
  "/team/:teamId",
  protect,
  controller.list.bind(controller),
);

////////////////////////////////////////////////////////////
// CHECK CURRENT USER MEMBERSHIP
////////////////////////////////////////////////////////////

router.get(
  "/team/:teamId/me",
  protect,
  controller.isMember.bind(controller),
);

////////////////////////////////////////////////////////////
// CHECK CURRENT USER ACTIVE MEMBERSHIP
////////////////////////////////////////////////////////////

router.get(
  "/team/:teamId/me/active",
  protect,
  controller.isActiveMember.bind(controller),
);

////////////////////////////////////////////////////////////
// FIND MEMBER
////////////////////////////////////////////////////////////

router.get(
  "/:memberId",
  protect,
  controller.findById.bind(controller),
);

////////////////////////////////////////////////////////////
// CHANGE ROLE
////////////////////////////////////////////////////////////

router.patch(
  "/:memberId/role",
  protect,
  controller.changeRole.bind(controller),
);

////////////////////////////////////////////////////////////
// SET STATUS
////////////////////////////////////////////////////////////

router.patch(
  "/:memberId/status",
  protect,
  controller.setStatus.bind(controller),
);

////////////////////////////////////////////////////////////
// ACTIVATE
////////////////////////////////////////////////////////////

router.patch(
  "/:memberId/activate",
  protect,
  controller.activate.bind(controller),
);

////////////////////////////////////////////////////////////
// DEACTIVATE
////////////////////////////////////////////////////////////

router.patch(
  "/:memberId/deactivate",
  protect,
  controller.deactivate.bind(controller),
);

////////////////////////////////////////////////////////////
// UPDATE
////////////////////////////////////////////////////////////

router.patch(
  "/:memberId",
  protect,
  controller.update.bind(controller),
);

////////////////////////////////////////////////////////////
// REMOVE
////////////////////////////////////////////////////////////

router.delete(
  "/:memberId",
  protect,
  controller.remove.bind(controller),
);

export default router;